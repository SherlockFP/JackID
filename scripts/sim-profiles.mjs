// Machine odds profiles (Tell Sheet, WAVE8_PLAN item 5). Plays every machine that exposes a `headless` play N times
// with the base modifiers (no charms, no luck) and writes src/game/data/machineProfiles.ts.
//
//   node scripts/sim-profiles.mjs                  200 000 plays per machine, writes the data file
//   node scripts/sim-profiles.mjs --plays 20000    quicker run (the file is still written)
//   node scripts/sim-profiles.mjs --only bigone,roulette --dry   print the table, write nothing
//
// Per machine, the multiplier of a play is gross / bet at def.minBet. The profile holds:
//   hit   P(multiplier > 0)              p2, p5, p10, p25, p100   P(multiplier >= x)
//   sigma standard deviation of the multiplier          rtp   mean multiplier (return to player)
//   cls   STEADY | SWINGY | WILD (thresholds below, on sigma)
// The run is deterministic: each machine gets its own seed from its id (hashSeed), so the file only changes when the
// machine code or the seed changes.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { load, closeVite, ROOT } from './tests/_vite.mjs';

const DEFAULT_PLAYS = 200_000;
/** sigma thresholds: below STEADY_MAX = STEADY, below SWINGY_MAX = SWINGY, otherwise WILD. */
const STEADY_MAX = 1.5;
const SWINGY_MAX = 4;
const TIERS = [2, 5, 10, 25, 100];
const OUT = join(ROOT, 'src', 'game', 'data', 'machineProfiles.ts');

const args = process.argv.slice(2);
const argVal = (name, def) => { const i = args.indexOf(name); return i >= 0 && args[i + 1] !== undefined ? args[i + 1] : def; };
const PLAYS = Math.max(1000, Number(argVal('--plays', DEFAULT_PLAYS)) | 0);
const ONLY = argVal('--only', '') ? new Set(argVal('--only', '').split(',').map((s) => s.trim()).filter(Boolean)) : null;
const DRY = args.includes('--dry');

/** The machine folders under src/machines (no `_base`), sorted, so the output file is stable. */
function machineIds() {
  const dir = join(ROOT, 'src', 'machines');
  return readdirSync(dir).filter((f) => !f.startsWith('_') && statSync(join(dir, f)).isDirectory()).sort();
}

/** FNV-1a 32-bit over the id: a stable per-machine seed (the run's own hashSeed is not needed here). */
function seedOf(id) {
  let h = 0x811c9dc5;
  for (let i = 0; i < id.length; i++) { h ^= id.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  return h >>> 0;
}

const r4 = (x) => Math.round(x * 1e4) / 1e4;
const r2 = (x) => Math.round(x * 100) / 100;

function classOf(sigma) {
  if (sigma < STEADY_MAX) return 'STEADY';
  if (sigma < SWINGY_MAX) return 'SWINGY';
  return 'WILD';
}

/** Plays one machine and returns its profile, or null when the machine has no headless play. */
async function profileOne(id, createRng) {
  const mod = await load(`src/machines/${id}/index.ts`);
  const def = mod.def;
  if (typeof def?.headless !== 'function') return null;
  const bet = def.minBet;
  const rng = createRng(seedOf(id));
  const hooks = { luck: 0, mod: (_hook, base) => base };
  const ge = new Array(TIERS.length).fill(0);
  let hits = 0, sum = 0, sumSq = 0;
  for (let i = 0; i < PLAYS; i++) {
    const gross = def.headless(rng, bet, hooks).gross;
    const m = gross / bet;
    if (gross > 0) hits++;
    sum += m;
    sumSq += m * m;
    for (let k = 0; k < TIERS.length; k++) if (m >= TIERS[k]) ge[k]++;
  }
  const mean = sum / PLAYS;
  const sigma = Math.sqrt(Math.max(0, sumSq / PLAYS - mean * mean));
  return {
    id, plays: PLAYS, bet,
    hit: r4(hits / PLAYS),
    p2: r4(ge[0] / PLAYS), p5: r4(ge[1] / PLAYS), p10: r4(ge[2] / PLAYS), p25: r4(ge[3] / PLAYS), p100: r4(ge[4] / PLAYS),
    sigma: r2(sigma), rtp: r4(mean), cls: classOf(sigma),
  };
}

function render(profiles) {
  const lines = profiles.map((p) => `  ${p.id}: { plays: ${p.plays}, bet: ${p.bet}, hit: ${p.hit}, p2: ${p.p2}, p5: ${p.p5}, ` +
    `p10: ${p.p10}, p25: ${p.p25}, p100: ${p.p100}, sigma: ${p.sigma}, rtp: ${p.rtp}, cls: '${p.cls}' },`);
  return [
    '// GENERATED by scripts/sim-profiles.mjs. Do not edit by hand: rerun the script after a machine odds change.',
    `// ${PLAYS} headless plays per machine at def.minBet, base modifiers only (no charms, no luck).`,
    '// hit = P(gross > 0); p2..p100 = P(multiplier >= x); sigma = s.d. of the multiplier; rtp = mean multiplier.',
    `// cls: STEADY sigma < ${STEADY_MAX}, SWINGY sigma < ${SWINGY_MAX}, WILD otherwise.`,
    '',
    "export type OddsClass = 'STEADY' | 'SWINGY' | 'WILD';",
    '',
    'export interface MachineProfile {',
    '  /** Plays the figures are based on. */',
    '  plays: number;',
    '  /** Stake the multiplier is measured at (def.minBet). */',
    '  bet: number;',
    '  /** P(the play pays anything). */',
    '  hit: number;',
    '  /** P(multiplier >= 2 / 5 / 10 / 25 / 100). */',
    '  p2: number; p5: number; p10: number; p25: number; p100: number;',
    '  /** Standard deviation of the multiplier per play. */',
    '  sigma: number;',
    '  /** Mean multiplier per play (return to player, before charms). */',
    '  rtp: number;',
    '  cls: OddsClass;',
    '}',
    '',
    '/** Keyed by machine id. Machines without a headless play have no entry (the odds line is then omitted). */',
    'export const MACHINE_PROFILES: Readonly<Record<string, MachineProfile>> = {',
    ...lines,
    '};',
    '',
    '/** The profile of a machine, or null. */',
    'export function profileOf(id: string): MachineProfile | null {',
    '  return Object.prototype.hasOwnProperty.call(MACHINE_PROFILES, id) ? MACHINE_PROFILES[id] : null;',
    '}',
    '',
  ].join('\n');
}

async function main() {
  const { createRng } = await load('src/core/rng.ts');
  const ids = machineIds().filter((id) => !ONLY || ONLY.has(id));
  const profiles = [];
  const t0 = Date.now();
  for (const id of ids) {
    const s = Date.now();
    try {
      const p = await profileOne(id, createRng);
      if (p) profiles.push(p);
      if (p) console.log(`${id.padEnd(14)} hit ${p.hit}  x2 ${p.p2}  x5 ${p.p5}  x10 ${p.p10}  x25 ${p.p25}  x100 ${p.p100}  sigma ${p.sigma}  rtp ${p.rtp}  ${p.cls}  (${Date.now() - s} ms)`);
      else console.log(`${id.padEnd(14)} no headless play, skipped`);
    } catch (e) {
      console.error(`${id}: FAILED ${e && e.message ? e.message : e}`);
      process.exitCode = 1;
    }
  }
  console.log(`${profiles.length} profile(s) in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
  if (DRY) return;
  if (ONLY) {
    console.log('--only given: not writing the data file (a partial table would drop machines). Rerun without --only.');
    return;
  }
  writeFileSync(OUT, render(profiles), 'utf8');
  console.log(`wrote ${OUT}`);
}

try {
  await main();
} finally {
  await closeVite();
}
